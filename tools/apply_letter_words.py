"""英字 1 字＋語（C言語、Tシャツ、X線、B型、Aランク）を、英字の名前の読みに読み替えて辞書の語として変換する。

  python tools/apply_letter_words.py <mozc/src>
apply_jaen_integration.py の最後から呼ばれる（英語の見分けの部分ごとの直しが入った後）。

「cgengo」は c が読めない子音で、打ち間違いとして消されて「言語」に、「bgata」は「b型」、「aranku」は「あらんく」に
なっていた（2026-11-07 利用者の報告「ｃげんごを変換すると言語になる」）。Mozc の辞書には「C言語」が「しーげんご」、
「Tシャツ」が「てぃーしゃつ」の読みで入っているので、打った英字をその英字の名前の読み（c → しー）に読み替えて、
辞書の語として変換させる。

読み替えるのは、辞書に「その英字の大文字＋日本語」の語があり、その読みが「英字の名前の読み＋続き」で、打った英字の
後ろのかなが、その続きの読みで始まる（かなの切れ目が合う）ときだけ。英字は、ローマ字として前後と組まずに残る
子音（c、b、x、t）だけ。母音（a ランク）は、お客（okyaku）が O脚 になるなど、ふつうのかなの語と重なるので替えない。
"""
import re
import sys
from pathlib import Path

src = Path(sys.argv[1])

# 英字の名前の読み → Mozc のローマ字（打った英字をこれに替える）。読みが 2 通りある英字は両方
NAMES = {
    "a": {"えー": "e-"}, "b": {"びー": "bi-"}, "c": {"しー": "shi-"}, "d": {"でぃー": "dhi-"},
    "e": {"いー": "i-"}, "f": {"えふ": "efu"}, "g": {"じー": "ji-"}, "h": {"えいち": "eichi", "えっち": "ecchi"},
    "i": {"あい": "ai"}, "j": {"じぇー": "je-"}, "k": {"けー": "ke-"}, "l": {"える": "eru"}, "m": {"えむ": "emu"},
    "n": {"えぬ": "enu"}, "o": {"おー": "o-"}, "p": {"ぴー": "pi-"}, "q": {"きゅー": "kyu-"}, "r": {"あーる": "a-ru"},
    "s": {"えす": "esu"}, "t": {"てぃー": "thi-"}, "u": {"ゆー": "yu-"}, "v": {"ぶい": "bui"},
    "w": {"だぶりゅー": "daburyu-"}, "x": {"えっくす": "ekkusu"}, "y": {"わい": "wai"}, "z": {"ぜっと": "zetto"},
}
SURFACE = re.compile(r"^[A-Z][^\x00-\x7f]+$")
HIRA = re.compile(r"^[ぁ-ゖー]+$")

entries = {}  # (英字, 続きの読み, 英字のキー) -> (費用, 語)
for f in sorted((src / "data/dictionary_oss").glob("dictionary*.txt")):
    for line in f.read_text(encoding="utf-8").splitlines():
        cols = line.split("\t")
        if len(cols) < 5 or not SURFACE.match(cols[4]) or not HIRA.match(cols[0]):
            continue
        letter = cols[4][0].lower()
        for name, keys in NAMES[letter].items():
            rest = cols[0][len(name):]
            if cols[0].startswith(name) and len(rest) >= 1:
                key = (letter, rest, keys)
                cost = int(cols[3])
                if key not in entries or cost < entries[key][0]:
                    entries[key] = (cost, cols[4])
rows = sorted((a, b, c, entries[(a, b, c)][1]) for a, b, c in entries)
print("letter words", len(rows))


def cstr(s):
    return '"' + s.replace("\\", "\\\\").replace('"', '\\"') + '"'


(src / "converter/letter_words_data.inc").write_text(
    "// Generated by tools/apply_letter_words.py from data/dictionary_oss: {letter, rest reading, letter keys, word}.\n"
    "inline constexpr const char* kLetterWords[][4] = {\n"
    + "".join(f"    {{{cstr(a)}, {cstr(b)}, {cstr(c)}, {cstr(d)}}},\n" for a, b, c, d in rows)
    + "};\n", encoding="utf-8", newline="\n")


def edit(path, old, new):
    p = src / path
    text = p.read_text(encoding="utf-8")
    if text.count(old) != 1:
        raise SystemExit(f"{path}: expected one match for {old[:60]!r}, found {text.count(old)}")
    p.write_text(text.replace(old, new), encoding="utf-8", newline="")


